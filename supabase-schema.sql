create table if not exists public.student_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Ученик',
  email text,
  role text not null default 'student' check (role in ('student','teacher','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_results (
  id bigint generated by default as identity primary key,
  student_id uuid not null references auth.users(id) on delete cascade,
  section text not null,
  score integer not null check (score >= 0),
  total integer not null check (total > 0 and score <= total),
  percentage integer not null check (percentage between 0 and 100),
  answers jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.writing_submissions (
  id bigint generated by default as identity primary key,
  student_id uuid not null references auth.users(id) on delete cascade,
  section text not null,
  kind text not null default 'retelling',
  prompt text,
  content text not null,
  created_at timestamptz not null default now()
);

alter table public.student_profiles enable row level security;
alter table public.quiz_results enable row level security;
alter table public.writing_submissions enable row level security;

-- SECURITY DEFINER avoids recursive profile-table RLS checks in role policies.
create or replace function public.english_lab_is_teacher()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.student_profiles p
    where p.id = auth.uid() and p.role in ('teacher','admin')
  );
$$;

create or replace function public.english_lab_create_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.student_profiles (id, display_name, email, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'display_name',''), 'Ученик'),
    new.email,
    'student'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists english_lab_auth_user_created on auth.users;
create trigger english_lab_auth_user_created
after insert on auth.users
for each row execute procedure public.english_lab_create_profile();

drop policy if exists "profile readable by owner or teacher" on public.student_profiles;
create policy "profile readable by owner or teacher"
on public.student_profiles for select to authenticated
using (id = auth.uid() or public.english_lab_is_teacher());

drop policy if exists "student inserts own quiz result" on public.quiz_results;
create policy "student inserts own quiz result"
on public.quiz_results for insert to authenticated
with check (student_id = auth.uid());

drop policy if exists "student reads own quiz result" on public.quiz_results;
create policy "student reads own quiz result"
on public.quiz_results for select to authenticated
using (student_id = auth.uid() or public.english_lab_is_teacher());

drop policy if exists "student inserts own writing" on public.writing_submissions;
create policy "student inserts own writing"
on public.writing_submissions for insert to authenticated
with check (student_id = auth.uid());

drop policy if exists "student reads own writing" on public.writing_submissions;
create policy "student reads own writing"
on public.writing_submissions for select to authenticated
using (student_id = auth.uid() or public.english_lab_is_teacher());

